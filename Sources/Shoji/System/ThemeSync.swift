import AppKit

/// When a theme is picked, carry it beyond Shoji (like Lucent's theme.sh does on Hyprland):
/// the macOS appearance, the wallpaper, kitty's colours and the macOS accent colour.
/// Each one can be turned off in Settings.
@MainActor
enum ThemeSync {
    static func apply(_ t: LucentTheme) {
        let c = Config.shared
        if c.themeSetsAppearance { setDarkMode(!t.isLight) }
        if c.themeSetsWallpaper { setWallpaper(light: t.isLight) }
        if c.themeSetsKitty { writeKitty(t) }
        if c.themeSetsAccent { setAccent(t.palette.mauve) }
    }

    // MARK: Appearance

    /// System Settings → Appearance: Dark for dark themes, Light for light ones. Done through
    /// System Events (public; macOS asks once to allow Shoji to control it).
    static func setDarkMode(_ dark: Bool) {
        let isDark = UserDefaults.standard.persistentDomain(forName: UserDefaults.globalDomain)?["AppleInterfaceStyle"] as? String == "Dark"
        guard dark != isDark else { return }
        let script = "tell application \"System Events\" to tell appearance preferences to set dark mode to \(dark)"
        DispatchQueue.global(qos: .userInitiated).async {
            var error: NSDictionary?
            NSAppleScript(source: script)?.executeAndReturnError(&error)
        }
    }

    // MARK: Wallpaper

    /// Lucent's starch lattice, in the render matching the theme's mode (dark or light), at the
    /// size closest to each screen's shape.
    static func setWallpaper(light: Bool) {
        guard let dir = Bundle.main.resourceURL?.appendingPathComponent("Wallpapers") else { return }
        for screen in NSScreen.screens {
            let wide = screen.frame.width / max(1, screen.frame.height) > 2.1
            let name = "starch-lattice\(light ? "-light" : "")-\(wide ? "5120x2160" : "3840x2160").png"
            let url = dir.appendingPathComponent(name)
            guard FileManager.default.fileExists(atPath: url.path) else { continue }
            try? NSWorkspace.shared.setDesktopImageURL(url, for: screen,
                                                      options: [.imageScaling: NSImageScaling.scaleProportionallyUpOrDown.rawValue,
                                                                .allowClipping: true])
        }
    }

    // MARK: kitty

    static var kittyThemeURL: URL {
        URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent(".config/kitty/theme.conf")
    }

    /// kitty's colours from the theme — the same mapping as Lucent's foot palette (theme.sh
    /// render_foot_palette) — written to ~/.config/kitty/theme.conf (which kitty.conf includes),
    /// then every running kitty is told to reload (SIGUSR1). The file that was there before Shoji
    /// first wrote it is kept as theme.conf.before-shoji.
    static func writeKitty(_ t: LucentTheme) {
        let fm = FileManager.default
        let url = kittyThemeURL
        guard fm.fileExists(atPath: url.deletingLastPathComponent().path) else { return } // no kitty config
        let backup = url.deletingLastPathComponent().appendingPathComponent("theme.conf.before-shoji")
        if fm.fileExists(atPath: url.path), !fm.fileExists(atPath: backup.path),
           let old = try? String(contentsOf: url, encoding: .utf8), !old.hasPrefix("# Generated by Shoji") {
            try? fm.copyItem(at: url, to: backup)
        }
        // A theme's `terminal` key names the theme whose palette the terminal gets.
        let p = t.terminal.flatMap(ThemeLibrary.theme)?.palette ?? t.palette
        func hex(_ c: NSColor) -> String { String(c.hexString.prefix(7)) }
        var lines = [
            "# Generated by Shoji from the \"\(t.name)\" theme — edits here are overwritten.",
            "# Your previous theme.conf is in theme.conf.before-shoji.",
            "",
            "foreground              \(hex(p.text))",
            "background              \(hex(p.base))",
            "selection_foreground    \(hex(p.base))",
            "selection_background    \(hex(p.rosewater))",
            "cursor                  \(hex(p.rosewater))",
            "cursor_text_color       \(hex(p.base))",
            "url_color               \(hex(p.rosewater))",
            "active_border_color     \(hex(p.mauve))",
            "inactive_border_color   \(hex(t.border ?? p.surface0))",
            "bell_border_color       \(hex(p.yellow))",
            "active_tab_foreground   \(hex(p.crust))",
            "active_tab_background   \(hex(p.mauve))",
            "inactive_tab_foreground \(hex(p.subtext))",
            "inactive_tab_background \(hex(p.mantle))",
            "tab_bar_background      \(hex(p.crust))",
            "",
        ]
        // Black and white assume a background: on a light theme black must be dark and white
        // light — the swap every light terminal scheme makes (as in Lucent).
        let (black, brightBlack, white, brightWhite) = p.isLight
            ? (p.subtext, p.overlay, p.surface1, p.surface0)
            : (p.surface1, p.overlay, p.subtext, p.text)
        let mid = [p.red, p.green, p.yellow, p.blue, p.pink, p.teal]
        let normal = [black] + mid + [white]
        let bright = [brightBlack] + mid + [brightWhite]
        for (i, c) in normal.enumerated() { lines.append("color\(i)  \(hex(c))") }
        for (i, c) in bright.enumerated() { lines.append("color\(i + 8)  \(hex(c))") }
        try? (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
        for app in NSRunningApplication.runningApplications(withBundleIdentifier: "net.kovidgoyal.kitty") {
            kill(app.processIdentifier, SIGUSR1) // kitty reloads its config on SIGUSR1
        }
    }

    // MARK: Accent colour

    /// The macOS accent colour nearest the theme's highlight (mauve) — macOS only offers eight.
    static func setAccent(_ color: NSColor) {
        let c = color.usingColorSpace(.sRGB) ?? color
        var h: CGFloat = 0, s: CGFloat = 0, b: CGFloat = 0, a: CGFloat = 0
        c.getHue(&h, saturation: &s, brightness: &b, alpha: &a)
        let deg = h * 360
        let (value, highlight): (Int, String)
        switch deg {
        case _ where s < 0.15: (value, highlight) = (-1, "0.847059 0.847059 0.862745 Graphite")
        case ..<15, 345...: (value, highlight) = (0, "1.000000 0.733333 0.721569 Red")
        case ..<45: (value, highlight) = (1, "1.000000 0.874510 0.701961 Orange")
        case ..<70: (value, highlight) = (2, "1.000000 0.937255 0.690196 Yellow")
        case ..<170: (value, highlight) = (3, "0.752941 0.964706 0.678431 Green")
        case ..<255: (value, highlight) = (4, "0.698039 0.843137 1.000000 Blue")
        case ..<300: (value, highlight) = (5, "0.968627 0.831373 1.000000 Purple")
        default: (value, highlight) = (6, "1.000000 0.749020 0.823529 Pink")
        }
        let global = kCFPreferencesAnyApplication
        let current = (CFPreferencesCopyAppValue("AppleAccentColor" as CFString, global) as? NSNumber)?.intValue
        guard current != value else { return }
        CFPreferencesSetAppValue("AppleAccentColor" as CFString, value as NSNumber, global)
        CFPreferencesSetAppValue("AppleHighlightColor" as CFString, highlight as CFString, global)
        CFPreferencesAppSynchronize(global)
        // What System Settings posts: running apps pick up the new colour.
        for name in ["AppleColorPreferencesChangedNotification", "AppleAquaColorVariantChanged"] {
            DistributedNotificationCenter.default().postNotificationName(NSNotification.Name(name), object: nil, userInfo: nil,
                                                                         deliverImmediately: true)
        }
    }
}
